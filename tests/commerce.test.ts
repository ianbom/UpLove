import assert from 'node:assert/strict';
import { filterProducts, validateCart, validateCustomer, createOrder, validateOrders, provinces, persistOrder, readShopStorage, storageKeys, parseJSON } from '../src/lib/commerce.ts';
import type { Product, Customer } from '../src/types/shop.ts';

const product: Product = { id: 'p1', slug: 'uplove', name: 'UpLove Kebaya', category: 'kebaya', collections: ['aluna'], price: 500000, description: 'Katun', material: 'Katun', care: 'Cuci tangan', images: ['/one.jpg'], variants: [{ id: 'ivory', color: 'Ivory', colorHex: '#fff', images: ['/one.jpg'], sizes: [{ size: 'M', stock: 3 }, { size: 'L', stock: 0 }] }], readyStock: true, newArrival: true, popularity: 9, createdAt: '2026-01-01' };
const products = [product, { ...product, id: 'p2', name: 'Amara Dress', category: 'dress' as const, price: 250000, readyStock: false, popularity: 2, createdAt: '2026-02-01' }];
const line = { productId: 'p1', variantId: 'ivory', size: 'M', quantity: 2 };
assert.deepEqual(validateCart(null, products), []);
assert.deepEqual(validateCart([{ ...line, quantity: -1 }, { ...line, productId: 'missing' }, { ...line, quantity: 1.5 }, { ...line, size: 'L' }], products), []);
assert.deepEqual(validateCart([line, { ...line, quantity: 2 }], products), [{ ...line, quantity: 3 }]);
assert.equal(filterProducts(products, { q: 'uplove' }).length, 1);
assert.equal(filterProducts(products, { category: 'kebaya', collection: 'aluna', size: 'M', color: 'ivory', availability: 'ready' }).length, 1);
assert.equal(filterProducts(products, { size: 'L' }).length, 0);
const soldOut = { ...product, id: 'sold-out', variants: [{ ...product.variants[0], sizes: [{ size: 'M', stock: 0 }] }] };
assert.equal(filterProducts([soldOut], {}).length, 1);
assert.equal(filterProducts([soldOut], { availability: 'ready' }).length, 0);
assert.equal(filterProducts(products, { sort: 'price-asc' })[0].id, 'p2');
assert.equal(filterProducts(products, { sort: 'newest' })[0].id, 'p2');
assert.equal(products[0].id, 'p1');
assert.equal(provinces.length, 38);
const customer: Customer = { name: 'Ayu Putri', email: 'ayu@example.com', phone: '081234567890', province: 'Bali', city: 'Denpasar', district: 'Denpasar Selatan', postalCode: '80222', address: 'Jalan Melati nomor 12', notes: '' };
assert.deepEqual(validateCustomer(customer), {});
assert.ok(validateCustomer({ ...customer, postalCode: '123', email: 'bad', province: 'unknown' }).postalCode);
const order = createOrder([line], customer, 'QRIS', products, 25000, 'UPLOVE-test', '2026-11-17T00:00:00.000Z');
assert.equal(order.total, 1025000);
assert.equal(order.items[0].unitPrice, 500000);
assert.equal(validateOrders([order], products, 25000).length, 1);
assert.equal(validateOrders([{ ...order, total: 1 }], products, 25000).length, 0);
assert.equal(validateOrders([{ ...order, items: [{ ...order.items[0], unitPrice: 1 }] }], products, 25000).length, 0);
const changedProducts = [{ ...product, price: 900000, variants: [{ ...product.variants[0], sizes: [{ size: 'M', stock: 0 }] }] }];
assert.deepEqual(validateOrders([order], changedProducts, 50000), [order]);
assert.deepEqual(validateOrders([order], [], 0), [order]);
assert.equal(validateOrders([{ ...order, items: [{ ...order.items[0], image: '//untrusted.example/image.jpg' }] }], products, 25000).length, 0);
assert.equal(validateOrders([{ ...order, items: [{ ...order.items[0], image: '/images/../secret.jpg' }] }], products, 25000).length, 0);
assert.equal(validateOrders([{ ...order, items: [{ ...order.items[0], quantity: 0 }] }], products, 25000).length, 0);
assert.throws(() => createOrder([{ ...line, quantity: 4 }], customer, 'QRIS', products, 25000, 'UPLOVE-test', new Date().toISOString()));
assert.throws(() => createOrder([line], customer, 'invalid', products, 25000, 'UPLOVE-test', new Date().toISOString()));
assert.throws(() => persistOrder({ getItem: () => null, setItem: () => { throw new Error('quota'); } }, order, products, 25000));
let saved = '';
persistOrder({ getItem: () => null, setItem: (_key: string, value: string) => { saved = value; } }, order, products, 25000);
assert.equal(JSON.parse(saved)[0].id, 'UPLOVE-test');
persistOrder({ getItem: () => JSON.stringify([order]), setItem: (_key: string, value: string) => { saved = value; } }, { ...order, id: 'UPLOVE-next' }, changedProducts, 50000);
assert.deepEqual(JSON.parse(saved).map((row: { id: string }) => row.id), ['UPLOVE-next', 'UPLOVE-test']);
const legacyLine = { ...line, productId: 'selara-001' };
const legacyOrder = { ...order, id: 'SEL-existing', customer: { ...customer, notes: 'selara-001 is my original note' }, items: [{ ...order.items[0], productId: legacyLine.productId }] };
const stored = new Map<string, string>([
  ['selara-cart-v1', JSON.stringify([legacyLine])],
  ['selara-wishlist-v1', JSON.stringify([legacyLine.productId])],
  ['selara-orders-v1', JSON.stringify([legacyOrder])],
]);
const storage = { getItem: (key: string) => stored.get(key) ?? null, setItem: (key: string, value: string) => { stored.set(key, value); } };
assert.deepEqual(parseJSON(readShopStorage(storage, storageKeys.cart)), [{ ...line, productId: 'uplove-001' }]);
assert.deepEqual(parseJSON(readShopStorage(storage, storageKeys.wishlist)), ['uplove-001']);
const migrated = validateOrders(parseJSON(readShopStorage(storage, storageKeys.orders)));
assert.equal(migrated[0].id, 'UPLOVE-existing');
assert.equal(migrated[0].items[0].productId, 'uplove-001');
assert.equal(migrated[0].customer.notes, legacyOrder.customer.notes);
assert.equal(migrated[0].total, legacyOrder.total);
assert.equal(stored.get('selara-orders-v1'), JSON.stringify([legacyOrder]));
stored.set(storageKeys.cart, '[]');
assert.equal(readShopStorage(storage, storageKeys.cart), '[]');
assert.equal(readShopStorage({ getItem: key => key === 'selara-wishlist-v1' ? '["selara-001"]' : null, setItem: () => { throw new Error('quota'); } }, storageKeys.wishlist), '["uplove-001"]');
assert.equal(readShopStorage({ getItem: () => 'bad json', setItem: () => { throw new Error('unexpected write'); } }, storageKeys.cart), 'bad json');
console.log('Commerce assertions passed, including UpLove data migration.');
